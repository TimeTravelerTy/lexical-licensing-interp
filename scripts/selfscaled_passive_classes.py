"""Exploratory: passive-test classes with the equivalence margin scaled to each condition's own active effect.

The declared passive test classes every condition against delta_s = 0.2 x v's active O effect at the site. The
on-axis piece and the u_md interchange push less than v on actives too, so they are held to v's bar. This script
re-classes them with delta_c = 0.2 x the condition's own held-out active D(O), using the same classifier
(analyze_passive_test.classify / outcome) on the stored CIs. Nothing is re-run. Not a declared reading.

Sources:
  Gemma, OLMo: results/{m}/split_edit/summary_passive.csv, summary_active.csv (full, on, umd)
  Pythia: results/pythia/split_edit (full, on) and results/pythia/das_direction_check (u_md)

Writes reports/selfscaled_passive_classes.md.
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze_passive_test import classify, outcome  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SHORT = {"surface (object next)": "surface", "abstract (takes an object)": "abstract", "mixed": "mixed",
         "nothing moves (active-specific)": "nothing", "unresolved": "unresolved"}
KEYS = ["est", "lo95", "hi95", "lo90", "hi90"]


def rows_split_edit(model):
    p = pd.read_csv(ROOT / f"results/{model}/split_edit/summary_passive.csv")
    a = pd.read_csv(ROOT / f"results/{model}/split_edit/summary_active.csv")
    out = []
    for cond in ["full", "on", "umd"]:
        if not (a.condition == cond).any():
            continue
        for s in sorted(p.site.unique()):
            act = float(a[(a.site == s) & (a.condition == cond)].dO_est.iloc[0])
            ci = {ro: {k: float(p[(p.site == s) & (p.readout == ro)][f"{cond}_{k}"].iloc[0]) for k in KEYS}
                  for ro in ["O", "by"]}
            out.append((model, cond, int(s), act, ci))
    return out


def rows_pythia_umd():
    p = pd.read_csv(ROOT / "results/pythia/das_direction_check/summary_passive_patching.csv")
    a = pd.read_csv(ROOT / "results/pythia/das_direction_check/summary_active_patching.csv")
    out = []
    for s in sorted(p.site.unique()):
        act = float(a[(a.site == s) & (a.direction == "u_md")].dO_est.iloc[0])
        ci = {ro: {k: float(p[(p.site == s) & (p.readout == ro)][f"umd_{k}"].iloc[0]) for k in KEYS}
              for ro in ["O", "by"]}
        out.append(("pythia", "umd", int(s), act, ci))
    return out


def main():
    rows = rows_split_edit("pythia") + rows_pythia_umd() + rows_split_edit("gemma") + rows_split_edit("olmo")
    recs = []
    for model, cond, s, act, ci in rows:
        d = 0.2 * act
        cO, cb = classify(ci["O"], d), classify(ci["by"], d)
        recs.append(dict(model=model, condition=cond, site=s, delta_c=d, O=ci["O"]["est"], by=ci["by"]["est"],
                         class_O=cO, class_by=cb, outcome=SHORT.get(outcome(cO, cb), outcome(cO, cb))))
    df = pd.DataFrame(recs)
    out = ROOT / "results/selfscaled_passive_classes.csv"
    df.to_csv(out, index=False)

    lines = ["# Passive outcomes with a self-scaled margin (exploratory)", "",
             "Generated by `scripts/selfscaled_passive_classes.py` from stored summaries; nothing re-run. Same "
             "classifier as the declared passive test, with δ_c = 0.2 × the condition's own held-out active D(O) "
             "in place of 0.2 × v's. Not a declared reading: chosen after seeing the split-edit results, because "
             "the declared δ holds the on-axis piece and u_md to v's active effect.", ""]
    for model in ["pythia", "gemma", "olmo"]:
        sub = df[df.model == model]
        conds = [c for c in ["full", "on", "umd"] if (sub.condition == c).any()]
        sites = sorted(sub.site.unique())
        lines += [f"## {model}", "", "| Site | " + " | ".join(f"{c} (δ_c)" for c in conds) + " |",
                  "|---:|" + "---|" * len(conds)]
        for s in sites:
            cells = []
            for c in conds:
                r = sub[(sub.condition == c) & (sub.site == s)]
                if len(r):
                    r = r.iloc[0]
                    cells.append(f"{r.outcome} ({r.delta_c:.2f}; by {r.by:+.2f} {r.class_by}, O {r.O:+.2f} {r.class_O})")
                else:
                    cells.append("")
            lines.append(f"| {s} | " + " | ".join(cells) + " |")
        lines.append("")
    (ROOT / "reports/selfscaled_passive_classes.md").write_text("\n".join(lines))
    print(df.pivot_table(index=["model", "site"], columns="condition", values="outcome", aggfunc="first").to_string())


if __name__ == "__main__":
    main()
